"""Import the submitted I/O list into the HMI.

Reads the IO List (hardwired) and Comms Point List (communication) sheets of the
Device and I/O List workbook and writes hmi/js/iolist.js, so the HMI tag database
is exactly the list submitted to the client.

Usage: python3 tools/import_io_list.py [workbook] [out.js]
"""
import json, os, re, sys
import openpyxl

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'docs', 'Villa_Somalia_SCADA_Device_and_IO_List_Rev1.xlsx')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'hmi', 'js', 'iolist.js')

UNIT = {'deg C': '°C', 'kohm': 'kΩ', 'W/m2': 'W/m²', 'deg': '°', '-': '', None: ''}
ENUM_CODES = ('STATE', 'MODE', 'FLT-CODE', 'ALM-CODE', 'CB-POS')


def lvl(x):
    x = str(x or '').strip()
    m = re.match(r'^([123])\b', x)
    return int(m.group(1)) if m else None


wb = openpyxl.load_workbook(SRC, data_only=True)
tags = []

for r in wb['IO List'].iter_rows(min_row=2, values_only=True):
    if not r[0]:
        continue
    tag, desc, equip, loc, typ, row, module, mtype, ch, normal, alarm, opby, note = (list(r) + [None] * 13)[:13]
    t = {'id': tag, 'desc': desc, 'equip': equip, 'loc': loc, 'type': typ, 'src': 'HW',
         'addr': 'Row %s · %s ch %s' % (row, module, ch), 'row': row, 'normal': normal, 'opby': opby or '-', 'note': note or ''}
    level = lvl(alarm)
    if typ == 'DI' and level:
        t['alarm'] = {'level': level, 'on': 0 if normal == 'Normally closed' else 1}
    if typ == 'AI':
        m = re.search(r'=\s*([\d.]+)\s*-\s*([\d.]+)\s*(\S+)', normal or '')
        t['unit'] = m.group(3) if m else ''
        t['range'] = [float(m.group(1)), float(m.group(2))] if m else None
        if 'below' in str(alarm):
            t['lim'] = {'level': level, 'lo': float(re.search(r'below\s*([\d.]+)', alarm).group(1))}
        elif 'outside' in str(alarm):
            nominal = 110 if '110' in tag else 24
            t['lim'] = {'level': level, 'lo': round(nominal * 0.9, 1), 'hi': round(nominal * 1.15, 1)}
    tags.append(t)

for r in wb['Comms Point List'].iter_rows(min_row=2, values_only=True):
    if not r[0]:
        continue
    tag, device, point, dirn, dtype, unit, src, alarm, when, opby, note = (list(r) + [None] * 11)[:11]
    code = tag.split('-', 1)[1] if '-' in tag else tag
    if dirn == 'Write':
        typ = 'AO' if dtype == 'Setpoint' else 'DO'
    elif dtype in ('Measured', 'Counter'):
        typ = 'AI'
    elif any(code.endswith(c) for c in ENUM_CODES) or dtype == 'Double point':
        typ = 'ST'
    else:
        typ = 'DI'
    t = {'id': tag, 'desc': point, 'equip': device, 'type': typ, 'src': 'COM', 'addr': src, 'unit': UNIT.get(unit, unit),
         'opby': opby or '-', 'note': note or ''}
    level = lvl(alarm)
    if level and typ in ('DI', 'ST'):
        t['alarm'] = {'level': level, 'on': 0 if when == 'Off' else 1}
    tags.append(t)

ids = [t['id'] for t in tags]
assert len(ids) == len(set(ids)), 'duplicate tags'
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* Generated by tools/import_io_list.py from %s - do not edit by hand. */\n' % os.path.basename(SRC))
    f.write('var SCADA = (typeof window !== "undefined" ? window : globalThis).SCADA = (typeof window !== "undefined" ? window : globalThis).SCADA || {};\n')
    f.write('SCADA.iolistSource = %s;\n' % json.dumps(os.path.basename(SRC)))
    f.write('SCADA.iolist = [\n' + ',\n'.join(json.dumps(t, ensure_ascii=False) for t in tags) + '\n];\n')
hw = sum(1 for t in tags if t['src'] == 'HW')
print('wrote %s: %d tags (%d hardwired, %d communication)' % (OUT, len(tags), hw, len(tags) - hw))
from collections import Counter
print(Counter(t['type'] for t in tags), Counter(t['alarm']['level'] for t in tags if 'alarm' in t))
